import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

import type { Migration } from "./migrate";

/**
 * SOURCE OF TRUTH KEYWORDS: readMigrationFolder, renderMigrationsModule, migration bundle, drizzle-kit output
 * WHAT:  Reads drizzle-kit's migration folders and renders the src/migrations.ts module.
 * WHY:   One implementation shared by the bundle script and the staleness test, so the test
 *        compares exactly what the script would write. Node-only (uses the file system).
 * WHERE: scripts/bundle-migrations.ts, src/migrate.test.ts.
 */
export function readMigrationFolder(dir: string): Migration[] {
  return readdirSync(dir)
    .filter((name) => statSync(join(dir, name)).isDirectory())
    .toSorted()
    .map((id) => ({ id, sql: readFileSync(join(dir, id, "migration.sql"), "utf8") }));
}

export function renderMigrationsModule(migrations: readonly Migration[]): string {
  const entries = migrations.map(
    (m) => `  {\n    id: ${JSON.stringify(m.id)},\n    sql: ${JSON.stringify(m.sql)},\n  },`,
  );
  return [
    "// GENERATED by scripts/bundle-migrations.ts from migrations/*/migration.sql. Do not edit.",
    'import type { Migration } from "./migrate";',
    "",
    "/**",
    " * SOURCE OF TRUTH KEYWORDS: MIGRATIONS, bundled migrations, study schema SQL",
    " * WHAT:  The study database migrations in apply order, as SQL strings.",
    " * WHY:   Lets every platform migrate without reading files; regenerated with db:generate.",
    " * WHERE: migrate.ts (runMigrations default), tests.",
    " */",
    "export const MIGRATIONS: readonly Migration[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}
